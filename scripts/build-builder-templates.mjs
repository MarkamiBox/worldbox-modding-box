// Copies the main code file of nine guide pages into the Content builder's templates, so the
// builder hands out exactly the code the pages teach. Run it after editing one of these pages:
//
//   node scripts/build-builder-templates.mjs
//
// `npm test` fails when the committed templates no longer match the pages.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/tools/contentBuilder/templates.ts');

/** key -> [guide page, file name shown on the code block] */
export const SOURCES = {
  actor: ['20-custom-actors', 'HelloActors.cs'],
  building: ['19-custom-buildings', 'HelloBuildings.cs'],
  disaster: ['21-disasters', 'HelloDisasters.cs'],
  combat: ['30-projectiles-spells', 'HelloCombat.cs'],
  ai_job: ['22-custom-ai', 'HelloAI.cs'],
  decision: ['22-custom-ai', 'HelloDecisions.cs'],
  city_job: ['22-custom-ai', 'HelloCityJobs.cs'],
  plot: ['41-plots', 'HelloPlots.cs'],
  window: ['18-custom-windows', 'HelloWindow.cs'],
  biome: ['46-biomes', 'HelloBiomes.cs'],
  names: ['47-name-generators', 'HelloNames.cs'],
  book: ['48-books', 'HelloBooks.cs'],
  war: ['49-war-types', 'HelloWars.cs'],
  kingdom_ai: ['55-kingdom-ai', 'HelloKingdomAI.cs'],
  build_order: ['56-architecture-and-build-orders', 'HelloBuildOrders.cs'],
  phenotype: ['57-phenotypes', 'HelloPhenotypes.cs'],
  hud: ['58-canvas-and-hud', 'HelloHUD.cs'],
};

export function buildTemplates() {
  const result = {};
  for (const [key, [page, file]] of Object.entries(SOURCES)) {
    const md = fs.readFileSync(path.join(root, 'src/content/en/nml', `${page}.md`), 'utf8').replace(/\r\n/g, '\n');
    const header = '```csharp Mods/HelloBox/Code/' + file + '\n';
    const start = md.indexOf(header);
    if (start === -1) throw new Error(`${page}: no ${file} block`);
    const body = md.slice(start + header.length);
    result[key] = body.slice(0, body.indexOf('\n```'));
  }
  return result;
}

/** The generated module: one string per template. */
export function render(templates) {
  return `// Generated by scripts/build-builder-templates.mjs from the guide pages. Do not edit by hand.\n\nexport const TEMPLATES: Record<string, string> = ${JSON.stringify(templates, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(out, render(buildTemplates()));
  console.log(`wrote ${path.relative(root, out)}`);
}
